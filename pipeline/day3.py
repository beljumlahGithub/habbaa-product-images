BLOCK = ['مص', 'كس', 'لعن', 'بز', 'ثدي', 'علق', 'هور', 'جن']

def texts(c):
    t = c['hero'][1] + c['hero'][2] + [c['uses'][0]] + [l for _, l in c['uses'][1]] + [c['feat'][1]]
    for a, b in c['feat'][2]:
        t += [a, b]
    return t + c['alt']

bad = []
for k, c in FAM.items():
    full = re.sub(r'[\sً-ْ]', '', ' '.join(texts(c)))
    for t in texts(c):
        tt = re.sub(r'[\sً-ْ]', '', t)
        for b in BLOCK:
            if b in tt:
                bad.append((k, b, t))
if bad:
    print('BLOCKED', bad); sys.exit(1)

