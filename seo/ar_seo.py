def fam(s):
    k=s[7:]
    for p,ti,kw in FAM:
        if re.match(p,k): return ti,kw
    raise Exception(s)
out={}
for l in open('map.txt'):
    a,sku,s=l.split(); d=D[s]; ti,kw=fam(s)
    t=d['t']; parts=t.split('،')
    # insert ti as second clause if not present
    if ti.split('،')[0] not in t:
        parts.insert(1,' '+ti)
    t2='،'.join(parts)
    t2=re.sub(r'\s+',' ',t2).strip()
    if len(t2)>200: t2=t
    # keywords: merge old + new, drop words already in title, cap 249 bytes
    words=[]
    tw=set(re.findall(r'\w+',t2))
    for w in (kw+' '+(d.get('k') or '')).split():
        if w in tw or w in words: continue
        words.append(w)
    k=''
    for w in words:
        if len((k+' '+w).strip().encode())>249: break
        k=(k+' '+w).strip()
    out[a]={'ar':{'t':t2,'b':d['b'][:5],'d':d.get('d') or '','k':k},'en':None,'sku':sku}
json.dump(out,open('C8ar.json','w'),ensure_ascii=False)
